def first_message(
    name: str,
    stack: str,
    case: str,
    missing_fields: list[str] | None = None,
    topic_questions: list[str] | None = None,
    closing_question_override: str | None = None,
) -> str:
    variant = random.choice(FIRST_MESSAGE_VARIANTS)
    closing = (
        closing_question_override
        if closing_question_override is not None
        else _closing_question(topic_questions)
    )
    text = variant.format(
        name=name or "Здравствуйте",
        stack=stack or "—",
        case=case or "—",
        closing_question=closing,
    )
    if missing_fields:
        warning = _data_warning(missing_fields)
        text = text.replace(_DATA_WARNING_MARKER, f"{warning}\n\n{_DATA_WARNING_MARKER}", 1)
    return text


