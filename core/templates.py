# Закрывающий вопрос теперь варьируется НЕЗАВИСИМО от тела сообщения (доп. анти-бан энтропия) —
# если у задачи распознана тема с недостающими деталями (core/checklist.py: assess_topic), эти
# вопросы ЗАМЕНЯЮТ закрывающий вопрос вместо случайного выбора из списка ниже.
DEFAULT_CLOSING_QUESTIONS = [
    "Хотите ли вы что то еще добавить к своей задаче?",
    "Что-то ещё хотите добавить к задаче?",
    "Хотите что-то дополнить к задаче?",
    "Хотите что-нибудь добавить к задаче?",
]


def _closing_question(topic_questions: list[str] | None) -> str:
    if topic_questions:
        items = "\n".join(f"{i}) {q}" for i, q in enumerate(topic_questions, start=1))
        return f"Чтобы точнее оценить задачу, уточните, пожалуйста:\n{items}"
    return random.choice(DEFAULT_CLOSING_QUESTIONS)

# Чеклист целостности задачи (core/checklist.py) — если данных не хватает, это НЕ отдельное
# сообщение и не блокирует отправку: предупреждение вставляется прямо в основное первое
# сообщение, перед абзацем согласия на оплату (маркер ниже присутствует во всех вариантах
# FIRST_MESSAGE_VARIANTS).
_DATA_WARNING_MARKER = "❗️Важно"

_DATA_WARNING_REASONS = {
    "stack": "не указано минимум два сервиса, которые нужно связать между собой",
    "case": "не описана ни проблема, которую нужно решить, ни данные, которые нужно обработать",
}


def _data_warning(missing_fields: list[str]) -> str:
    reasons = "; ".join(_DATA_WARNING_REASONS[f] for f in missing_fields)
    return f"⚠️ Для точной оценки пока не хватает данных: {reasons}. Пожалуйста, дополните описание задачи."


