def first_message(name: str, stack: str, case: str, missing_fields: list[str] | None = None) -> str:
    variant = random.choice(FIRST_MESSAGE_VARIANTS)
    text = variant.format(name=name or "Здравствуйте", stack=stack or "—", case=case or "—")
    if missing_fields:
        warning = _data_warning(missing_fields)
        text = text.replace(_DATA_WARNING_MARKER, f"{warning}\n\n{_DATA_WARNING_MARKER}", 1)
    return text


def task_text_faq_answered(faq_id: str) -> str:
    return TASK_TEXT_FAQ_ANSWERED_TEMPLATE.format(faq_id=faq_id)
